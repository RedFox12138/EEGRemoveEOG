%% MATLAB版本指标计算与绘图使用说明
% 
% 文件: compute_all_metrics.m
% 作者: GitHub Copilot (基于Python版本改写)
% 日期: 2025-12-15
%
% ========================================================================
% 一、功能概述
% ========================================================================
% 
% 本MATLAB脚本完整实现了Python版本的所有功能：
% 1. 自动加载测试集真实纯净信号（Test_Pure.mat）
% 2. 自动扫描results文件夹下所有.mat预测结果文件
% 3. 提取方法名并计算4个评价指标：
%    - RRMSE: 相对均方根误差 (越小越好)
%    - CC: 相关系数 (越大越好)
%    - RRMSE_PSD: 功率谱相对误差 (越小越好)
%    - MI: 互信息 (越大越好)
% 4. 保存结果到CSV文件（格式：Mean ± Std）
% 5. 生成性能对比图（4个子图，带(a)(b)(c)(d)标识）
% 6. 生成运行时间对比图
%
% ========================================================================
% 二、使用方法
% ========================================================================
%
% 【方法1】直接在MATLAB命令行运行：
%
%   >> cd('D:\Pycharm_Projects\EOG Remove\复现的方法')
%   >> compute_all_metrics
%
% 【方法2】在脚本中调用：
%
%   compute_all_metrics();
%
% ========================================================================
% 三、输出文件
% ========================================================================
%
% 运行完成后会在 results 目录下生成以下文件：
%
% 1. all_metrics.csv - 所有方法的指标汇总表（CSV格式）
% 2. metrics_comparison.png - 性能对比图（高分辨率PNG，300dpi）
% 3. metrics_comparison.eps - 性能对比图（矢量图，适合论文）
% 4. time_comparison.png - 运行时间对比图（PNG格式）
% 5. time_comparison.eps - 运行时间对比图（矢量图）
%
% ========================================================================
% 四、图表说明
% ========================================================================
%
% 【性能对比图】(metrics_comparison)
% - 布局：2×2子图
% - 子图(a)：RRMSE指标（左上）
% - 子图(b)：CC指标（右上）
% - 子图(c)：RRMSE_PSD指标（左下）
% - 子图(d)：MI指标（右下）
% - 每个柱状图包含：
%   * 误差棒（标准差）
%   * 数值标签（保留3位小数）
%   * 彩色区分不同方法
%   * 网格线便于读数
%
% 【时间对比图】(time_comparison)
% - 单个图表，横向对比所有方法的运行时间
% - 单位：毫秒(ms)
% - 柱状图上方标注具体数值
%
% ========================================================================
% 五、指标计算方法
% ========================================================================
%
% 1. RRMSE (相对均方根误差):
%    RRMSE = sqrt(mean((y_true - y_pred)^2) / mean(y_true^2))
%
% 2. CC (相关系数):
%    CC = corrcoef(y_true, y_pred)
%
% 3. RRMSE_PSD (功率谱相对误差):
%    使用pwelch函数计算功率谱密度
%    RRMSE_PSD = sqrt(mean((PSD_true - PSD_pred)^2) / mean(PSD_true^2))
%
% 4. MI (互信息):
%    MI = sum(P(x,y) * log(P(x,y) / (P(x)*P(y))))
%    使用2D直方图估计联合概率分布
%
% ========================================================================
% 六、与Python版本的差异
